val configuredApiUrl = providers.gradleProperty("CLASSROOM_API_BASE_URL")
    .getOrElse("http://10.0.2.2:8080/")
    .let { if (it.endsWith("/")) it else "$it/" }

val releaseKeystorePath = providers.gradleProperty("CLASSROOM_KEYSTORE_PATH").orNull
val releaseKeystorePassword = providers.gradleProperty("CLASSROOM_KEYSTORE_PASSWORD").orNull
val releaseKeyAlias = providers.gradleProperty("CLASSROOM_KEY_ALIAS").orNull
val releaseKeyPassword = providers.gradleProperty("CLASSROOM_KEY_PASSWORD").orNull
val hasReleaseSigning = listOf(
    releaseKeystorePath,
    releaseKeystorePassword,
    releaseKeyAlias,
    releaseKeyPassword,
).all { !it.isNullOrBlank() }

